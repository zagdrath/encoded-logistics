"""The client-side search index: a script (assets/search-index.js) rather than JSON, so it loads from disk too."""

import json
import os
import re

from . import md, paths

SEGMENT = re.compile(r'<h([23]) id="([^"]+)"[^>]*>(.*?)</h\1>', re.S)


def clean(text, limit=None):
    text = md.strip_tags(text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:limit] if limit else text


def build(site):
    entries = []

    def add(kind, title, url, summary="", text="", extra=""):
        entries.append([kind, title, url, clean(summary, 200), clean(text, 6000), extra])

    for page in site.pages.values():
        if page.kind == "item":
            ident = page.entry
            add("item", page.title, page.url, getattr(page, "search_text", ""), "", ident)
            continue
        if page.kind == "command":
            c = page.command
            add("command", c["name"], page.url, c["description"], " ".join(p["keyword"] + " " + p["label"] for p in c["params"]))
            continue
        if page.kind in ("redirect", "search"):
            continue
        body = page.body or ""
        # The page itself, then each section under its h2/h3 heading.
        parts = SEGMENT.split(body)
        intro = parts[0]
        add("page", page.title, page.url, page.summary, intro)
        for k in range(1, len(parts), 4):
            level, ident, heading, text = parts[k], parts[k + 1], parts[k + 2], parts[k + 3] if k + 3 < len(parts) else ""
            heading_text = clean(re.sub(r'<a class="anchor".*?</a>', "", heading))
            add("heading", heading_text, page.url + "#" + ident, "", text, page.title)
    for path, o in site.data.config_options.items():
        add("config", path, site.config_url(path), (o.get("label") or "") + ". " + (o.get("comment") or "").split("\n")[0], "", o["file"])
    for ident, m in site.data.messages.items():
        add("message", ident, site.message_url(ident), m["text"])
    out = os.path.join(paths.SITE, "assets", "search-index.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/docs/build.py. [kind, title, url, summary, text, extra] */\n")
        f.write("window.EL_SEARCH=")
        json.dump(entries, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    return len(entries)
