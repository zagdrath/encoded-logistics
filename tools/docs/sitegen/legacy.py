"""The old single-page Terminal OS and ELCL reference (terminal-os-elcl.html) as a redirect: each of its anchors goes to
the page and section that now covers it. The map is generated from the pages: a heading carries the old anchors it
replaces as {#id legacy="old other"}, a page's front matter as legacy: [old], and the generated command and message
references add their own. #cmd-NAME goes to that command's page."""

import html
import json
import os

from . import checks, paths


def anchor_map(site):
    mapping = {}
    for page in site.pages.values():
        for old, ident in page.legacy.items():
            if old in mapping and mapping[old] != page.url + ("#" + ident if ident else ""):
                site.problems.append("old anchor #%s is claimed by two pages (%s and %s)" % (old, mapping[old], page.url))
            mapping[old] = page.url + ("#" + ident if ident else "")
    return mapping


def write(site):
    mapping = anchor_map(site)
    old = checks.legacy_anchors()
    for anchor in old:
        if anchor not in mapping:
            site.problems.append("the old page's #%s has no new home: add legacy=\"%s\" to the heading that covers it" % (anchor, anchor))
    commands = sorted(site.data.commands)
    titles = {}
    with open(os.path.join(paths.NOTES, "legacy-anchors.txt"), encoding="utf-8") as f:
        for line in f:
            if line.strip() and not line.startswith("#"):
                key, _, title = line.rstrip("\n").partition("\t")
                titles[key] = title
    for prefix, target in (("", os.path.join(paths.SITE, "terminal-os-elcl.html")), ("site/", paths.OLD_PAGE)):
        items = "".join('<li><a href="%s">%s</a></li>' % (html.escape(prefix + mapping[a]), html.escape(titles.get(a) or a))
                        for a in old if a in mapping)
        page = TEMPLATE % {
            "map": json.dumps({k: prefix + v for k, v in sorted(mapping.items())}, separators=(",", ":")),
            "commands": json.dumps(commands, separators=(",", ":")),
            "prefix": prefix,
            "home": html.escape(prefix + "elcl/index.html"),
            "items": items,
        }
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(page)
    return mapping


TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Terminal OS and ELCL Reference (moved)</title>
<link rel="canonical" href="%(home)s">
<script>
/* Generated by tools/docs/build.py: the old single-page reference's anchors and where they went. */
(function () {
  var map = %(map)s;
  var commands = %(commands)s;
  var anchor = decodeURIComponent(location.hash.slice(1));
  var target = map[anchor];
  var m = /^cmd-([A-Za-z0-9@#$]+)$/.exec(anchor);
  if (!target && m && commands.indexOf(m[1].toUpperCase()) >= 0) {
    target = "%(prefix)selcl/commands/" + m[1].toUpperCase() + ".html";
  }
  location.replace(target || "%(prefix)selcl/index.html");
})();
</script>
<noscript><meta http-equiv="refresh" content="0; url=%(home)s"></noscript>
<style>body{font:16px/1.6 system-ui,sans-serif;max-width:46rem;margin:2rem auto;padding:0 16px;color:#1c1f22;background:#fbfaf7}a{color:#1d5fa8}
@media (prefers-color-scheme: dark){body{background:#14171a;color:#e4e6e8}a{color:#79b8ff}}</style>
</head>
<body>
<h1>This reference has moved</h1>
<p>The Terminal OS and ELCL reference is now part of the <a href="%(home)s">Encoded Logistics documentation</a>, split into pages. If you
aren't taken there, pick the section you were looking for:</p>
<ul>%(items)s</ul>
</body>
</html>
"""
