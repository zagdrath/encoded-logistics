CELL_W, CELL_H, COLUMNS = 4, 6, 16

if __name__ == '__main__':
    assert len(G) == 95, len(G)
    sheet = Image.new('RGBA', (COLUMNS * CELL_W, 7 * CELL_H), (0, 0, 0, 0))
    for c, rows in G.items():
        assert len(rows) == 5 and all(len(r) == 3 for r in rows), c
        i = ord(c) - 32
        x0, y0 = i % COLUMNS * CELL_W, i // COLUMNS * CELL_H
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == '#':
                    sheet.putpixel((x0 + x, y0 + y), (255, 255, 255, 255))
    sheet.save('src/main/resources/assets/encodedlogistics/textures/font/terminal_small.png')
    print('ok')
