CW,CH=6,10
def sheet():
    """96 x 60 font sheet: 16 columns x 6 rows of 6x10 cells, ASCII 32-127; white glyphs, alpha elsewhere."""
    from PIL import Image
    im=Image.new('RGBA',(16*CW,6*CH),(0,0,0,0))
    for code in range(32,128):
        ch=chr(code); rows=G.get(ch,G['?']); i=code-32; ox,oy=(i%16)*CW,(i//16)*CH
        for ry,row in enumerate(rows):
            for rx,v in enumerate(row):
                if v=='#': im.putpixel((ox+rx,oy+1+ry),(255,255,255,255))
    return im
